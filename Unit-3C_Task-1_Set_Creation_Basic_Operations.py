set_a = {1, 2, 3, 4}  # e.g. {1, 2, 3, 4}
set_b = {3, 4, 5, 6}  # e.g. {3, 4, 5, 6}

print("Set A:", set_a)
print("Set B:", set_b)
print("Union:", set_a | set_b)  # set_a | set_b
print("Intersection:", set_a & set_b)  # set_a & set_b
print("Difference (A - B):", set_a - set_b)  # set_a - set_b