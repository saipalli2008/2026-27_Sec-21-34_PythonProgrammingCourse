#python comparision operators
a=29
b=14
result = a==b # equal to comparision
print("result of",a, "==",b,"is : ",result)

result = a!=b #not equalto comparison
print("result of",a, "!=",b,"is : ",result)

result = a > b #greaterthan comparison
print("result of",a, ">",b,"is : ",result)

result = a < b #lessthan comparision
print("result of",a, "<",b,"is : ",result)

result = a >= b #greaterthan or equalto comparison
print("result of",a, ">=",b,"is : ",result)

result = a <= b #lessthan or equalto comparision
print("result of",a, "<=",b,"is : ",result)